const topicsByCourse = {
  "daily-english": dailyFocusTopics,
  "kids-english": foundationTopics,
  "grammar-english": governanceTopics,
  "pattern-english": caseTopics,
  "chat-english": qaTopics,
};

function publishDate(day) {
  const date = new Date(startDate);
  date.setUTCDate(startDate.getUTCDate() + day);
  return date;
}

function itemForCourse(courseId, day) {
  const topics = topicsByCourse[courseId];
  if (!topics) {
    throw new Error(`Unknown course: ${courseId}`);
  }

  const topic = topics[day % topics.length];
  const round = Math.floor(day / topics.length) + 1;
  const note = frameNotes[Math.floor(day / topics.length) % frameNotes.length];

  return {
    sentence: round === 1 ? topic[0] : `${topic[0]}（第 ${round} 輪複習）`,
    translation: topic[1],
    grammarNote: topic[2],
    usageNote: note,
    vocabulary: topic[3],
    example: topic[4],
  };
}

async function main() {
  const targetCourses = selectedCourseIds.size
    ? courses.filter((course) => selectedCourseIds.has(course.id))
    : courses;

  if (targetCourses.length === 0) {
    throw new Error(`No matching courses for SEED_COURSES=${process.env.SEED_COURSES}`);
  }

  for (const course of targetCourses) {
    await prisma.course.upsert({
      where: { id: course.id },
      update: {
        slug: course.slug,
        name: course.name,
        description: course.description,
      },
      create: course,
    });
  }

  for (const course of targetCourses) {
    for (let day = 0; day < 365; day += 1) {
      const data = {
        ...itemForCourse(course.id, day),
        courseId: course.id,
        publishDate: publishDate(day),
      };

      await prisma.dailySentence.upsert({
        where: {
          courseId_publishDate: {
            courseId: course.id,
            publishDate: data.publishDate,
          },
        },
        update: data,
        create: data,
      });
    }
  }

  const counts = await prisma.dailySentence.groupBy({
    by: ["courseId"],
    _count: { _all: true },
    orderBy: { courseId: "asc" },
  });

  console.table(
    counts.map((row) => ({
      courseId: row.courseId,
      count: row._count._all,
    })),
  );
}

main()
  .catch((error) => {
    console.error(error);
    process.exitCode = 1;
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
